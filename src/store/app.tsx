import {
  createContext,
  useCallback,
  useContext,
  useMemo,
  useRef,
  useState,
  type ReactNode,
} from 'react';

import {
  MOCK_JOBS,
  MOCK_NOTIFICATIONS_SEED,
  MOCK_OUTREACH_SEED,
  MOCK_PROFILE,
  MOCK_TRACKER_ROWS,
} from '@/mocks/data';
import type { Job, NotificationItem, OutreachItem } from '@/types';

/**
 * Phase 1 in-memory store, mock data only. The shape mirrors what the real
 * backend endpoints will return in Phase 3 so screens swap cleanly later.
 * A right swipe runs the locked optimistic flow: instant confirmation,
 * a "drafting" placeholder in the Inbox, then the item fills in after a
 * simulated async delay.
 */

const DRAFT_SIMULATION_MS = 4500;

const FIXTURE_CONTACTS = [
  { name: 'Alex Fixture', title: 'Senior Associate' },
  { name: 'Riley Mockwell', title: 'Vice President' },
  { name: 'Casey Specimen', title: 'Engagement Manager' },
  { name: 'Morgan Sampleton', title: 'Senior Product Manager' },
];

type ToastState = { message: string; showInboxAction: boolean } | null;

type Profile = typeof MOCK_PROFILE;

type AppStore = {
  jobs: Job[];
  outreach: OutreachItem[];
  notifications: NotificationItem[];
  trackerRows: typeof MOCK_TRACKER_ROWS;
  profile: Profile;
  toast: ToastState;
  unreadCount: number;
  canUndo: boolean;
  passJob: (id: string) => void;
  draftJob: (id: string) => void;
  undoLastPass: () => void;
  resetDeck: () => void;
  updateOutreach: (id: string, patch: Partial<OutreachItem>) => void;
  markOutreachSent: (id: string) => void;
  markNotificationsRead: () => void;
  showToast: (message: string, showInboxAction?: boolean) => void;
};

const AppContext = createContext<AppStore | null>(null);

export function AppProvider({ children }: { children: ReactNode }) {
  const [jobs, setJobs] = useState<Job[]>(MOCK_JOBS);
  const [outreach, setOutreach] = useState<OutreachItem[]>(MOCK_OUTREACH_SEED);
  const [notifications, setNotifications] = useState<NotificationItem[]>(
    MOCK_NOTIFICATIONS_SEED,
  );
  const [profile, setProfile] = useState<Profile>(MOCK_PROFILE);
  const [toast, setToast] = useState<ToastState>(null);

  const passedStack = useRef<Job[]>([]);
  const idCounter = useRef(0);
  const contactCounter = useRef(0);
  const toastTimer = useRef<ReturnType<typeof setTimeout> | null>(null);

  const showToast = useCallback((message: string, showInboxAction = false) => {
    if (toastTimer.current) clearTimeout(toastTimer.current);
    setToast({ message, showInboxAction });
    toastTimer.current = setTimeout(() => setToast(null), 3200);
  }, []);

  const passJob = useCallback((id: string) => {
    setJobs((prev) => {
      const job = prev.find((j) => j.id === id);
      if (job) passedStack.current.push(job);
      return prev.filter((j) => j.id !== id);
    });
  }, []);

  const undoLastPass = useCallback(() => {
    const job = passedStack.current.pop();
    if (job) setJobs((prev) => [job, ...prev]);
  }, []);

  const resetDeck = useCallback(() => {
    passedStack.current = [];
    setJobs(MOCK_JOBS);
  }, []);

  const updateOutreach = useCallback(
    (id: string, patch: Partial<OutreachItem>) => {
      setOutreach((prev) =>
        prev.map((item) => (item.id === id ? { ...item, ...patch } : item)),
      );
    },
    [],
  );

  const draftJob = useCallback(
    (id: string) => {
      const job = jobs.find((j) => j.id === id);
      if (!job) return;

      idCounter.current += 1;
      const outreachId = `out-new-${idCounter.current}`;

      setJobs((prev) => prev.filter((j) => j.id !== id));
      setOutreach((prev) => [
        {
          id: outreachId,
          jobTitle: job.title,
          company: job.company,
          status: 'drafting',
          timeLabel: 'Just now',
        },
        ...prev,
      ]);
      setProfile((prev) => ({
        ...prev,
        credits: prev.credits - prev.creditsPerSwipe,
        dailyDraftsUsed: prev.dailyDraftsUsed + 1,
      }));
      showToast(`Outreach drafted, -${profile.creditsPerSwipe} credits`, true);

      // Simulated async backend job: contact found, draft written.
      const fixture =
        FIXTURE_CONTACTS[contactCounter.current % FIXTURE_CONTACTS.length];
      contactCounter.current += 1;
      setTimeout(() => {
        setOutreach((prev) =>
          prev.map((item) =>
            item.id === outreachId
              ? {
                  ...item,
                  status: 'ready',
                  contact: {
                    name: fixture.name,
                    title: fixture.title,
                    company: job.company,
                  },
                  subject: `Student reaching out about ${job.title}`,
                  snippet: 'Draft is ready for your review (mock)',
                  body: `Hi ${fixture.name.split(' ')[0]},\n\nFixture draft body generated by the mock service for the ${job.title} role at ${job.company}. Edit me to test the editor.\n\nBest,\nSample Student`,
                }
              : item,
          ),
        );
        setNotifications((prev) => [
          {
            id: `n-new-${outreachId}`,
            kind: 'draft_ready',
            text: `Your outreach to ${fixture.name} at ${job.company} is ready to review`,
            timeLabel: 'Just now',
            read: false,
            outreachId,
          },
          ...prev,
        ]);
      }, DRAFT_SIMULATION_MS);
    },
    [jobs, profile.creditsPerSwipe, showToast],
  );

  const markOutreachSent = useCallback(
    (id: string) => {
      updateOutreach(id, {
        status: 'sent',
        snippet: 'Sent from your connected Gmail (mock)',
        timeLabel: 'Just now',
      });
    },
    [updateOutreach],
  );

  const markNotificationsRead = useCallback(() => {
    setNotifications((prev) => prev.map((n) => ({ ...n, read: true })));
  }, []);

  const unreadCount = notifications.filter((n) => !n.read).length;

  const value = useMemo<AppStore>(
    () => ({
      jobs,
      outreach,
      notifications,
      trackerRows: MOCK_TRACKER_ROWS,
      profile,
      toast,
      unreadCount,
      canUndo: passedStack.current.length > 0,
      passJob,
      draftJob,
      undoLastPass,
      resetDeck,
      updateOutreach,
      markOutreachSent,
      markNotificationsRead,
      showToast,
    }),
    [
      jobs,
      outreach,
      notifications,
      profile,
      toast,
      unreadCount,
      passJob,
      draftJob,
      undoLastPass,
      resetDeck,
      updateOutreach,
      markOutreachSent,
      markNotificationsRead,
      showToast,
    ],
  );

  return <AppContext.Provider value={value}>{children}</AppContext.Provider>;
}

export function useApp() {
  const ctx = useContext(AppContext);
  if (!ctx) throw new Error('useApp must be used inside AppProvider');
  return ctx;
}
